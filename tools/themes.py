"""Check every theme in themes/ and regenerate the catalogue in themes/README.md.

    python tools/themes.py           # check, then rewrite the catalogue in themes/README.md and themes/catalogue.js
    python tools/themes.py --check   # check only; exit 1 on a problem or an out-of-date catalogue (used by CI)

A theme is a folder themes/<name>/ with theme.js, theme.json (manifest) and README.md. The check makes sure the
manifest is complete, that the names it lists are exactly the ones theme.js registers, and that no name is used twice
across the core and all themes (decks can link several themes at once, so names are global).
Python 3, standard library only.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES = os.path.join(ROOT, "themes")
CATALOGUE = os.path.join(THEMES, "README.md")
DEMO_DATA = os.path.join(THEMES, "catalogue.js")         # read by themes/demo.html and demo-stage.html
START, END = "<!-- catalogue:start (generated by tools/themes.py, do not edit by hand) -->", "<!-- catalogue:end -->"
KINDS = [("transitions", "Transitions", "data-enter"), ("effects", "Element effects", "data-fx"),
         ("ambients", "Ambient backgrounds", "data-ambient"), ("dots", "Progress dot styles", "data-dots")]
ONE = {"transitions": "transition", "effects": "effect", "ambients": "ambient", "dots": "dot style"}


def count(n, kind):
    return f"{n} {ONE[kind] if n == 1 else kind.replace('dots', 'dot styles')}"
REQUIRED = ["name", "title", "description", "author", "tags", "provides"]


def core_names():
    js = open(os.path.join(ROOT, "engine.js"), encoding="utf-8").read()
    trans = set(re.findall(r"\bT\['([\w-]+)'\]\s*=", js)) | set(re.findall(r"\bT\.(\w+)\s*=", js))
    fx = set(re.findall(r"'([\w-]+)'", re.search(r"const CORE_FX = \[(.*?)\];", js).group(1))) - {"none"}
    amb = set(re.findall(r"\bAMBIENTS\.(\w+)\s*=", js))
    dots = set(re.findall(r"\bDOTSTYLES\.(\w+)\s*=", js))
    return {"transitions": trans, "effects": fx, "ambients": amb, "dots": dots}


def registered(js):
    """names a theme.js registers, by kind"""
    trans = set(re.findall(r"se\.transition\(\s*'([\w-]+)'", js)) | set(re.findall(r"\bT\['([\w-]+)'\]\s*=", js)) | set(re.findall(r"\bT\.(\w+)\s*=", js))
    return {"transitions": trans, "effects": set(re.findall(r"se\.build\(\s*'([\w-]+)'", js)),
            "ambients": set(re.findall(r"se\.ambient\(\s*'([\w-]+)'", js)), "dots": set(re.findall(r"se\.dots\(\s*'([\w-]+)'", js))}


def load_themes(errors):
    themes = []
    for d in sorted(os.listdir(THEMES)) if os.path.isdir(THEMES) else []:
        path = os.path.join(THEMES, d)
        if not os.path.isdir(path):
            continue
        where = f"themes/{d}"
        for f in ("theme.js", "theme.json", "README.md"):
            if not os.path.isfile(os.path.join(path, f)):
                errors.append(f"{where}: missing {f}")
        try:
            m = json.load(open(os.path.join(path, "theme.json"), encoding="utf-8"))
        except (OSError, ValueError) as e:
            errors.append(f"{where}/theme.json: {e}")
            continue
        for k in REQUIRED:
            if k not in m:
                errors.append(f"{where}/theme.json: missing \"{k}\"")
        if m.get("name") != d:
            errors.append(f"{where}/theme.json: name \"{m.get('name')}\" must equal the folder name \"{d}\"")
        if not re.fullmatch(r"[a-z][a-z0-9-]*", d):
            errors.append(f"{where}: folder name must be lowercase letters, digits and dashes")
        prov = {k: list(m.get("provides", {}).get(k, [])) for k, _, _ in KINDS}
        extra = set(m.get("provides", {})) - {k for k, _, _ in KINDS}
        if extra:
            errors.append(f"{where}/theme.json: unknown kinds in provides: {', '.join(sorted(extra))}")
        if os.path.isfile(os.path.join(path, "theme.js")):
            js = open(os.path.join(path, "theme.js"), encoding="utf-8").read()
            if not re.search(r"slideEngineThemes.*?\.push\(\s*\{\s*name:\s*'%s'" % re.escape(d), js, re.S):
                errors.append(f"{where}/theme.js: must push {{ name: '{d}', setup(se) {{ ... }} }} onto window.slideEngineThemes")
            reg = registered(js)
            for k, label, _ in KINDS:
                if set(prov[k]) != reg[k]:
                    miss, more = reg[k] - set(prov[k]), set(prov[k]) - reg[k]
                    if miss:
                        errors.append(f"{where}: theme.js registers {k} not listed in theme.json: {', '.join(sorted(miss))}")
                    if more:
                        errors.append(f"{where}: theme.json lists {k} that theme.js doesn't register: {', '.join(sorted(more))}")
        if "accent" in m and not re.fullmatch(r"#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?", str(m["accent"])):
            errors.append(f"{where}/theme.json: accent must be a #rgb or #rrggbb colour")
        names = {n for k, _, _ in KINDS for n in prov[k]}
        for n in m.get("preview", {}):
            if n not in names:
                errors.append(f"{where}/theme.json: preview for \"{n}\", which the theme doesn't provide")
        demo = m.get("demo")
        if demo and not os.path.isfile(os.path.join(ROOT, demo)):
            errors.append(f"{where}/theme.json: demo {demo} not found")
        m["provides"] = prov
        themes.append(m)
    return themes


def check_unique(core, themes, errors):
    for k, _, _ in KINDS:
        owner = {n: "core" for n in core[k]}
        for t in themes:
            for n in t["provides"][k]:
                if n in owner:
                    errors.append(f"{k[:-1]} \"{n}\" in theme {t['name']} is already used by {owner[n]}")
                owner[n] = t["name"]


def catalogue(core, themes):
    out = [START, ""]
    out += ["### All themes", "", "| theme | what it is | adds | tags | demo |", "|---|---|---|---|---|"]
    out.append("| **core** (built into `engine.js`) | neutral: cube turns, iris, blinds, dissolve, zoom, vortex and the automatic element builds | "
               + ", ".join(count(len(core[k]), k) for k, _, _ in KINDS if core[k]) + " | | [showcase](../demo/showcase/deck.html) |")
    for t in sorted(themes, key=lambda t: t["name"]):
        adds = ", ".join(count(len(t["provides"][k]), k) for k, _, _ in KINDS if t["provides"][k])
        demo = f"[{os.path.basename(os.path.dirname(t['demo']))}](../{t['demo']})" if t.get("demo") else ""
        out.append(f"| [**{t['name']}**]({t['name']}/README.md) | {t['description']} | {adds} | {', '.join(sorted(t['tags']))} | {demo} |")
    for k, label, attr in KINDS:
        rows = [(n, "core") for n in core[k]] + [(n, t["name"]) for t in themes for n in t["provides"][k]]
        if not rows:
            continue
        out += ["", f"### {label} (`{attr}`), A–Z", "", "| name | theme |", "|---|---|"]
        out += [f"| `{n}` | {th if th == 'core' else f'[{th}]({th}/README.md)'} |" for n, th in sorted(rows)]
    tags = {}
    for t in themes:
        for tag in t["tags"]:
            tags.setdefault(tag, []).append(t["name"])
    if tags:
        out += ["", "### By tag", "", "| tag | themes |", "|---|---|"]
        out += [f"| {tag} | {', '.join(f'[{n}]({n}/README.md)' for n in sorted(ns))} |" for tag, ns in sorted(tags.items())]
    out += ["", END]
    return "\n".join(out)


def demo_data(core, themes):
    """themes/catalogue.js: everything the theme demo page lists, core first"""
    data = {"core": {k: sorted(core[k]) for k, _, _ in KINDS},
            "themes": [{"name": t["name"], "title": t["title"], "description": t["description"], "accent": t.get("accent"),
                        "options": t.get("options", {}), "preview": t.get("preview", {}),
                        "provides": {k: sorted(t["provides"][k]) for k, _, _ in KINDS}} for t in sorted(themes, key=lambda t: t["name"])]}
    return ("/* Generated by tools/themes.py from engine.js and every themes/<name>/theme.json; do not edit by hand.\n"
            "   Used by themes/demo.html and themes/demo-stage.html. */\n"
            "window.SE_CATALOGUE = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


def main():
    check_only = "--check" in sys.argv
    errors = []
    core = core_names()
    themes = load_themes(errors)
    check_unique(core, themes, errors)
    text = open(CATALOGUE, encoding="utf-8").read()
    if START not in text or END not in text:
        errors.append("themes/README.md: catalogue markers missing")
    if errors:
        print("\n".join("ERROR " + e for e in errors))
        sys.exit(1)
    new = text[:text.index(START)] + catalogue(core, themes) + text[text.index(END) + len(END):]
    data = demo_data(core, themes)
    old_data = open(DEMO_DATA, encoding="utf-8").read() if os.path.isfile(DEMO_DATA) else ""
    if check_only:
        if new != text or data != old_data:
            print("ERROR themes/README.md catalogue or themes/catalogue.js is out of date: run python tools/themes.py")
            sys.exit(1)
        print(f"themes OK ({len(themes)} theme{'s' if len(themes) != 1 else ''})")
        return
    if new != text:
        open(CATALOGUE, "w", encoding="utf-8", newline="\n").write(new)
        print("themes/README.md catalogue updated")
    if data != old_data:
        open(DEMO_DATA, "w", encoding="utf-8", newline="\n").write(data)
        print("themes/catalogue.js updated")
    print(f"themes OK ({len(themes)} theme{'s' if len(themes) != 1 else ''})")


if __name__ == "__main__":
    main()
